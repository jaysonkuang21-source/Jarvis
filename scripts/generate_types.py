"""Emit the TypeScript mirror of app.models.

Run after changing any model:
    uv run python scripts/generate_types.py

Emits plain type aliases rather than TS enums because the frontend compiles
with ``erasableSyntaxOnly``, which forbids enums.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pydantic import BaseModel  # noqa: E402

from app import models as m  # noqa: E402
from app import scheduler as sched  # noqa: E402
from app import security as sec  # noqa: E402

OUTPUT = Path(__file__).resolve().parent.parent / "frontend" / "src" / "lib" / "api" / "types.ts"

